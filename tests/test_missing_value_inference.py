"""A missing value does not prove a negative claim about its defining document."""
from pathlib import Path
import sys
import unittest

sys.path[:0] = [str(Path(__file__).resolve().parents[1] / 'prototype'),
               str(Path(__file__).resolve().parent)]
from test_one_call_answers import answer, one_call


SERVICE = ('7.2. Срок сервисного обслуживания определяется исполнителем '
           'и указывается в сервисном паспорте.')
FILES = {'Договор обслуживания.txt': 'Договор обслуживания\n' + SERVICE}
INFERENCE = ('Само по себе отсутствие значения в отсылочном положении не доказывает, '
             'что названное в вопросе значение не могло быть установлено.')


class MissingValueInferenceTests(unittest.TestCase):
    def test_negative_inference_is_answered_without_confirming_the_unknown_value(self):
        for question, invented in (
                ('В договоре вместо числа дана отсылка к исполнителю и паспорту. '
                 'Означает ли отсутствие числа в самом договоре, что исполнитель точно '
                 'не мог установить срок сервисного обслуживания 19 месяцев?', '19 месяцев'),
                ('Доказывает ли отсутствие срока в договоре, что исполнитель не мог '
                 'установить срок сервисного обслуживания два года?', 'два года'),
                ('Подтверждает ли само отсутствие значения в договоре, что исполнитель '
                 'не может предусмотреть срок сервисного обслуживания 43 месяца?', '43 месяца')):
            with self.subTest(question=question):
                bad = 'Да, исполнитель не мог установить срок сервисного обслуживания ' + invented + '.'
                result, _, _ = one_call(question, [answer('7.2.', bad)] * 2, FILES)
                self.assertEqual(result['status'], 'partial')
                self.assertTrue(result['text'].startswith(INFERENCE), result['text'])
                self.assertIn('Конкретное значение в найденных документах не установлено:', result['text'])
                self.assertIn('«' + SERVICE + '»', result['text'])
                self.assertIn('Чтобы назвать значение, нужен этот документ.', result['text'])
                self.assertNotIn(invented, result['text'])
                self.assertNotIn(bad, result['text'])

    def test_fee_inference_does_not_depend_on_contract_warranty_or_months(self):
        source = ('3.6. Размер комиссии устанавливается оператором '
                  'и указывается в тарифном приложении.')
        files = {'Правила обслуживания.txt': 'Правила обслуживания\n' + source}
        question = ('Означает ли отсутствие размера в правилах, что оператор '
                    'не мог установить комиссию 8 процентов?')
        result, _, _ = one_call(question, [answer('3.6.', 'Комиссия составляет 8 процентов.')] * 2, files)
        self.assertTrue(result['text'].startswith(INFERENCE), result['text'])
        self.assertIn('тарифном приложении', result['text'])
        self.assertNotIn('8 процентов', result['text'])

    def test_other_questions_keep_the_unknown_value_response_without_an_extra_inference(self):
        for question in (
                'Срок сервисного обслуживания ведь 19 месяцев?',
                'Не означает ли отсутствие числа, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев?',
                'Означает ли отсутствие числа, что без паспорта нельзя определить срок сервисного обслуживания 19 месяцев?',
                'Означает ли отсутствие числа, что исполнитель мог не установить срок сервисного обслуживания 19 месяцев?',
                'Означает ли не отсутствие числа, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев?',
                'Означает ли отсутствие числа, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев или мог установить два года?',
                'Означает ли отсутствие числа в договоре и прямой запрет закона, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев?',
                'Означает ли отсутствие числа в договоре вместе с прямым запретом закона, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев?',
                'Означает ли отсутствие числа либо прямой запрет закона, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев?',
                'Означает ли отсутствие числа, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев и комиссию 8 процентов?',
                'Означает ли отсутствие числа, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев вместе с комиссией 8 процентов?',
                'Означает ли отсутствие числа, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев? А срок ведь 20 месяцев?',
                'Пользователь: Означает ли отсутствие числа, что исполнитель не мог установить срок сервисного обслуживания 19 месяцев?\n'
                'Ассистент: Срок неизвестен.\nПользователь: Срок сервисного обслуживания ведь 20 месяцев?'):
            with self.subTest(question=question):
                result, _, _ = one_call(question, [answer('7.2.', 'Срок сервисного обслуживания составляет 19 месяцев.')] * 2, FILES)
                self.assertNotIn(INFERENCE, result['text'])

    def test_no_missing_defining_document_means_no_application_inference(self):
        files = {**FILES, 'Сервисный паспорт.txt':
                 'СЕРВИСНЫЙ ПАСПОРТ\n1.1. Срок сервисного обслуживания составляет 19 месяцев.'}
        question = ('Означает ли отсутствие числа в договоре, что исполнитель не мог '
                    'установить срок сервисного обслуживания 19 месяцев?')
        prose = 'В сервисном паспорте установлен срок сервисного обслуживания 19 месяцев (п. 1.1).'
        result, _, _ = one_call(question, [answer('1.1.', prose)], files)
        self.assertEqual(result['status'], 'answer')
        self.assertNotIn(INFERENCE, result['text'])
        self.assertIn('19 месяцев', result['text'])


if __name__ == '__main__':
    unittest.main()
